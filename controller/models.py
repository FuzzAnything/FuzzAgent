"""Pydantic models for the FuzzAgent Controller API and internal task representation."""

import enum
from datetime import datetime, timezone

from pydantic import BaseModel, Field


class TaskStatusEnum(str, enum.Enum):
    PENDING = "pending"
    RUNNING = "running"
    COMPLETED = "completed"
    FAILED = "failed"
    CANCELLED = "cancelled"


# --- API Request Models ---


class FuzzingTaskCreate(BaseModel):
    task_id: str = Field(..., description="Unique task ID generated by Backend")
    container_name: str = Field(..., description="Container name for easier identification")
    command: str = Field(..., description="Semantic command: 'fuzz' or 'analysis'")
    fuzzagent_dir: str = Field(..., description="Host path to the Storage-prepared FuzzAgent directory")
    raw_output_dir: str = Field(..., description="Host path for raw fuzzing output")
    repo_base_name: str = Field(..., description="Base name for repo, e.g. 'cjson' or 'openssl'")
    src_dir: str = Field(..., description="Host path to the target library source code")
    fuzzing_engine: str = Field(default="afl++", description="Fuzzing engine: 'afl++' or 'libfuzzer'")
    llm_model: str = Field(..., description="LLM model name")
    openai_base_url: str = Field(..., repr=False, description="OpenAI base URL")
    openai_api_key: str = Field(..., repr=False, description="OpenAI API key")
    # Per-model LLM tuning. Forwarded into the fuzz container's env.
    llm_temperature: float = Field(default=0.6)
    llm_top_p: float = Field(default=0.9)
    llm_top_k: int = Field(default=20)
    llm_reply_timeout: int = Field(default=600)
    max_agent_epochs: int = Field(default=100)
    reminder_token_ratio: float = Field(default=0.8)
    max_token_len: int = Field(default=128000)
    callback_url: str | None = Field(default=None, description="URL to POST task status on completion")
    callback_token: str | None = Field(default=None, repr=False, description="Bearer token for callback POST")
    enable_analysis: bool = Field(default=True, description="Automatically run statistics analysis after task completes")
    config: dict | None = Field(default=None, description="Scan configuration overrides (extra_env, fuzzing_duration_hours, etc.)")


# --- API Response Models ---


class FuzzingTaskResponse(BaseModel):
    task_id: str
    status: TaskStatusEnum
    container_id: str | None = None
    created_at: datetime
    started_at: datetime | None = None
    finished_at: datetime | None = None
    error_message: str | None = None
    analysis_status: str | None = None


class FuzzingTaskListResponse(BaseModel):
    tasks: list[FuzzingTaskResponse]
    total: int


class AnalysisResponse(BaseModel):
    task_id: str
    analysis_status: str | None = None
    analysis_container_id: str | None = None


class HealthResponse(BaseModel):
    status: str = "ok"
    version: str
    uptime_seconds: float
    docker: str = "ok"


# --- Internal Task Model ---


class FuzzingTask(BaseModel):
    task_id: str = Field(...)
    status: TaskStatusEnum = TaskStatusEnum.PENDING
    container_name: str = Field(..., description="Container name for easier identification")
    command: str = Field(..., description="Semantic command: 'fuzz' or 'analysis'")
    fuzzagent_dir: str = Field(..., description="Host path to the Storage-prepared FuzzAgent directory")
    write_mode: bool = Field(default=False, description="Derived from command: fuzz=True, analysis=False")
    raw_output_dir: str = Field(..., description="Host path for raw fuzzing output")
    repo_base_name: str = Field(..., description="Base name for repo, e.g. 'cjson' or 'openssl'")
    src_dir: str = Field(..., description="Host path to the target library source code")
    fuzzing_engine: str = Field(default="afl++", description="Fuzzing engine: 'afl++' or 'libfuzzer'")
    auto_clean: bool = Field(default=True, description="Derived from command: fuzz=True, analysis=False")
    llm_model: str = Field(..., description="LLM model name")
    disable_coverage_guidance: bool = Field(default=False, description="Disable coverage-guided fuzzing")
    openai_base_url: str = Field(..., repr=False, description="OpenAI base URL")
    openai_api_key: str = Field(..., repr=False, description="OpenAI API key")
    # Per-model LLM tuning. Forwarded into the fuzz container's env via the
    # compose template (see compose_generator + docker_template.yml).
    llm_temperature: float = Field(default=0.6)
    llm_top_p: float = Field(default=0.9)
    llm_top_k: int = Field(default=20)
    llm_reply_timeout: int = Field(default=600)
    max_agent_epochs: int = Field(default=100)
    reminder_token_ratio: float = Field(default=0.8)
    max_token_len: int = Field(default=128000)
    extra_env: dict[str, str] = Field(default_factory=dict, description="Additional env vars for container")
    callback_url: str | None = Field(default=None, description="URL to POST task status on completion")
    callback_token: str | None = Field(default=None, repr=False, description="Bearer token for callback POST")
    enable_analysis: bool = Field(default=True, description="Automatically run statistics analysis after task completes")
    config: dict | None = Field(default=None, description="Scan configuration overrides")
    fuzzing_duration_hours: int | None = Field(default=None, description="Max fuzzing duration in hours")

    container_id: str | None = None
    analysis_container_id: str | None = None
    analysis_status: str | None = None
    compose_dir: str | None = None

    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    started_at: datetime | None = None
    finished_at: datetime | None = None

    error_message: str | None = None
    exit_code: int | None = None

    def to_response(self) -> FuzzingTaskResponse:
        return FuzzingTaskResponse(
            task_id=self.task_id,
            status=self.status,
            container_id=self.container_id,
            created_at=self.created_at,
            started_at=self.started_at,
            finished_at=self.finished_at,
            error_message=self.error_message,
            analysis_status=self.analysis_status,
        )
